from transformers import pipeline

# Using the modern text-generation pipeline as recommended by transformers v5
generator = pipeline("text-generation", model="gpt2")

text = """
Artificial Intelligence is one of the most important technologies
in the modern world. It is used in healthcare, education,
banking, transportation and many other fields. AI helps machines
learn from data, solve problems and make decisions.
It saves time and improves efficiency in different industries.
"""

# Constructing a prompt to ask the model to summarize the text
prompt = f"Summarize the following text in one short sentence:\n\nText: {text}\n\nSummary:"

outputs = generator(prompt, max_new_tokens=50, num_return_sequences=1, clean_up_tokenization_spaces=True)

print("Original Text:")
print(text)

print("\nSummarized Text:")
summary_text = outputs[0]['generated_text'][len(prompt):].strip()
print(summary_text if summary_text else "(Model did not generate a summary)")