import os
import shutil
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.naive_bayes import MultinomialNB
from sklearn.pipeline import Pipeline

documents = [
    "Python programming and machine learning",
    "Artificial intelligence and deep learning",
    "Bank account transaction and financial report",
    "Loan application and banking details",
    "Student examination and college results",
    "University admission and education system"
]

labels = [
    "Technology", "Technology",
    "Finance", "Finance",
    "Education", "Education"
]

model = Pipeline([
    ("tfidf", TfidfVectorizer()),
    ("classifier", MultinomialNB())
])

model.fit(documents, labels)

new_documents = [
    "Machine learning and artificial intelligence",
    "Bank loan and financial transaction",
    "Student college examination"
]

os.makedirs("Classified_Documents", exist_ok=True)

for i, doc in enumerate(new_documents):
    category = model.predict([doc])[0]

    folder = os.path.join("Classified_Documents", category)
    os.makedirs(folder, exist_ok=True)

    file_path = os.path.join(folder, f"document_{i+1}.txt")

    with open(file_path, "w") as file:
        file.write(doc)

    print(f"Document {i+1} classified as: {category}")

print("Documents separated successfully!")