from textblob import TextBlob
import pandas as pd

data = {
    "Review": [
        "The product quality is excellent and I am very happy.",
        "The service was amazing and very fast.",
        "The product is good and works perfectly.",
        "The quality is very poor and disappointing.",
        "I am unhappy with the service.",
        "The product is bad and stopped working.",
        "The service was okay.",
        "The product is average."
    ]
}

df = pd.DataFrame(data)

def get_sentiment(review):
    polarity = TextBlob(review).sentiment.polarity

    if polarity > 0:
        return "Positive"
    elif polarity < 0:
        return "Negative"
    else:
        return "Neutral"

df["Sentiment"] = df["Review"].apply(get_sentiment)

print("Opinion Mining Results:\n")
print(df.to_string(index=False))

print("\nSentiment Count:")
print(df["Sentiment"].value_counts())