import re
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.naive_bayes import MultinomialNB

documents = [
    "Name: Ankit\nSubject: AI\nMarks: 90",
    "Name: Rahul\nSubject: ML\nMarks: 85",
    "Name: Priya\nSubject: NLP\nMarks: 95"
]

X = ["name subject marks", "name subject marks", "name subject marks"]
y = ["START", "START", "START"]

vectorizer = CountVectorizer()
X_vector = vectorizer.fit_transform(X)

model = MultinomialNB()
model.fit(X_vector, y)

text = """
Name: Ankit
Subject: AI
Marks: 90
Name: Rahul
Subject: ML
Marks: 85
Name: Priya
Subject: NLP
Marks: 95
"""

lines = [line.strip() for line in text.split("\n") if line.strip()]

state = "OUTSIDE"
current_document = []
documents_found = []

for line in lines:
    features = re.sub(r"[^a-zA-Z ]", "", line.lower())
    features = vectorizer.transform([features])

    probability = model.predict_proba(features).max()

    is_boundary = line.lower().startswith("name:") and probability > 0.5

    if is_boundary:
        if current_document:
            documents_found.append(current_document)
        current_document = [line]
        state = "INSIDE"

    elif state == "INSIDE":
        current_document.append(line)

if current_document:
    documents_found.append(current_document)

for i, doc in enumerate(documents_found, 1):
    print(f"\nDocument {i}:")
    print("\n".join(doc))

print("\nTotal Documents:", len(documents_found))