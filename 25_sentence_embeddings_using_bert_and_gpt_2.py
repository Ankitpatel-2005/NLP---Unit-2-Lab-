import torch
from transformers import BertTokenizer, BertModel, GPT2Tokenizer, GPT2Model

sentences = [
    "I love machine learning",
    "Deep learning is interesting",
    "Natural language processing is useful"
]

bert_tokenizer = BertTokenizer.from_pretrained("bert-base-uncased")
bert_model = BertModel.from_pretrained("bert-base-uncased")

bert_inputs = bert_tokenizer(
    sentences,
    return_tensors="pt",
    padding=True,
    truncation=True
)

with torch.no_grad():
    bert_outputs = bert_model(**bert_inputs)

bert_embeddings = bert_outputs.last_hidden_state.mean(dim=1)

print("BERT Sentence Embeddings:")
print(bert_embeddings.shape)
print(bert_embeddings)

gpt_tokenizer = GPT2Tokenizer.from_pretrained("gpt2")
gpt_tokenizer.pad_token = gpt_tokenizer.eos_token

gpt_model = GPT2Model.from_pretrained("gpt2")

gpt_inputs = gpt_tokenizer(
    sentences,
    return_tensors="pt",
    padding=True,
    truncation=True
)

with torch.no_grad():
    gpt_outputs = gpt_model(**gpt_inputs)

gpt_embeddings = gpt_outputs.last_hidden_state.mean(dim=1)

print("GPT-2 Sentence Embeddings:")
print(gpt_embeddings.shape)
print(gpt_embeddings)