import numpy as np
import tensorflow as tf
from tensorflow.keras.layers import Input, Dense, Softmax, Multiply, Lambda
from tensorflow.keras.models import Model

X = np.random.rand(100, 10, 8)
y = np.random.randint(0, 2, 100)

inputs = Input(shape=(10, 8))

attention = Dense(1, activation='tanh')(inputs)
attention = Softmax(axis=1)(attention)

context = Multiply()([inputs, attention])
context = Lambda(lambda x: tf.reduce_sum(x, axis=1))(context)

outputs = Dense(1, activation='sigmoid')(context)

model = Model(inputs, outputs)

model.compile(
    optimizer='adam',
    loss='binary_crossentropy',
    metrics=['accuracy']
)

model.summary()

model.fit(X, y, epochs=10, batch_size=8)

loss, accuracy = model.evaluate(X, y)

print("Accuracy:", accuracy)

predictions = model.predict(X[:5])
print("Predictions:")
print(predictions)